CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(32) NOT NULL UNIQUE
        CHECK (username ~ '^[a-z0-9_]{3,32}$'),
    password_hash VARCHAR(255) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS genres (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(60) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS platforms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(60) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS games (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(120) NOT NULL,
    release_year SMALLINT CHECK (release_year BETWEEN 1970 AND 2100),
    genre_id BIGINT NOT NULL REFERENCES genres(id) ON DELETE RESTRICT,
    CONSTRAINT games_title_genre_unique UNIQUE (title, genre_id)
);

CREATE TABLE IF NOT EXISTS collection_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    game_id BIGINT NOT NULL REFERENCES games(id) ON DELETE RESTRICT,
    platform_id BIGINT NOT NULL REFERENCES platforms(id) ON DELETE RESTRICT,
    status VARCHAR(12) NOT NULL DEFAULT 'backlog'
        CHECK (status IN ('backlog', 'playing', 'completed')),
    rating SMALLINT NOT NULL DEFAULT 0 CHECK (rating BETWEEN 0 AND 10),
    hours_played INTEGER NOT NULL DEFAULT 0 CHECK (hours_played BETWEEN 0 AND 9999),
    favorite BOOLEAN NOT NULL DEFAULT FALSE,
    note TEXT NOT NULL DEFAULT '',
    added_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT collection_user_game_platform_unique UNIQUE (user_id, game_id, platform_id)
);

CREATE INDEX IF NOT EXISTS collection_user_status_idx ON collection_items(user_id, status);
CREATE INDEX IF NOT EXISTS collection_user_added_idx ON collection_items(user_id, added_at DESC);
CREATE INDEX IF NOT EXISTS games_genre_id_idx ON games(genre_id);

